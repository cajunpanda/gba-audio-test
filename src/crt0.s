@ crt0.s - GBA cartridge header + startup for a dependency-free build.
@ Layout must match the GBA cart header exactly: branch, Nintendo logo,
@ title/code fields, then entry code at offset 0xC0.

    .section .gba_header, "ax"
    .arm
    .global _start_header
_start_header:
    b   _start                      @ 0x00: branch to entry (offset 0xC0)

    @ 0x04: 156-byte Nintendo boot logo (required by BIOS to boot on hardware)
    .byte 0x24,0xff,0xae,0x51,0x69,0x9a,0xa2,0x21,0x3d,0x84,0x82,0x0a,0x84,0xe4,0x09,0xad
    .byte 0x11,0x24,0x8b,0x98,0xc0,0x81,0x7f,0x21,0xa3,0x52,0xbe,0x19,0x93,0x09,0xce,0x20
    .byte 0x10,0x46,0x4a,0x4a,0xf8,0x27,0x31,0xec,0x58,0xc7,0xe8,0x33,0x82,0xe3,0xce,0xbf
    .byte 0x85,0xf4,0xdf,0x94,0xce,0x4b,0x09,0xc1,0x94,0x56,0x8a,0xc0,0x13,0x72,0xa7,0xfc
    .byte 0x9f,0x84,0x4d,0x73,0xa3,0xca,0x9a,0x61,0x58,0x97,0xa3,0x27,0xfc,0x03,0x98,0x76
    .byte 0x23,0x1d,0xc7,0x61,0x03,0x04,0xae,0x56,0xbf,0x38,0x84,0x00,0x40,0xa7,0x0e,0xfd
    .byte 0xff,0x52,0xfe,0x03,0x6f,0x95,0x30,0xf1,0x97,0xfb,0xc0,0x85,0x60,0xd6,0x80,0x25
    .byte 0xa9,0x63,0xbe,0x03,0x01,0x4e,0x38,0xe2,0xf9,0xa2,0x34,0xff,0xbb,0x3e,0x03,0x44
    .byte 0x78,0x00,0x90,0xcb,0x88,0x11,0x3a,0x94,0x65,0xc0,0x7c,0x63,0x87,0xf0,0x3c,0xaf
    .byte 0xd6,0x25,0xe4,0x8b,0x38,0x0a,0xac,0x72,0x21,0xd4,0xf8,0x07

    @ 0xA0: 12-byte game title
    .ascii "AUDIOTEST   "
    @ 0xAC: 4-byte game code
    .ascii "AATE"
    @ 0xB0: 2-byte maker code
    .ascii "00"
    @ 0xB2: fixed value
    .byte 0x96
    @ 0xB3: main unit code
    .byte 0x00
    @ 0xB4: device type
    .byte 0x00
    @ 0xB5..0xBB: 7 reserved bytes
    .byte 0x00,0x00,0x00,0x00,0x00,0x00,0x00
    @ 0xBC: software version
    .byte 0x00
    @ 0xBD: complement check (patched by tools/gbafix.py post-link)
    .byte 0x00
    @ 0xBE..0xBF: 2 reserved bytes
    .byte 0x00,0x00

    @ 0xC0: entry point
    .align 2
    .global _start
_start:
    @ IRQ mode, IRQ+FIQ disabled, set IRQ stack
    mov     r0, #0xD2
    msr     cpsr_c, r0
    ldr     sp, =0x03007FA0
    @ System mode, set user/system stack
    mov     r0, #0xDF
    msr     cpsr_c, r0
    ldr     sp, =__stack_top

    @ copy .data (LMA in ROM) -> IWRAM
    ldr     r0, =__data_lma
    ldr     r1, =__data_start
    ldr     r2, =__data_end
1:  cmp     r1, r2
    ldrlo   r3, [r0], #4
    strlo   r3, [r1], #4
    blo     1b

    @ zero .bss
    ldr     r1, =__bss_start
    ldr     r2, =__bss_end
    mov     r3, #0
2:  cmp     r1, r2
    strlo   r3, [r1], #4
    blo     2b

    @ enter C
    ldr     r0, =main
    bx      r0
3:  b       3b

    .pool
    .align 2
